/** TalkBack (architecture 2.5): each half of a right/wrong drawing is its own role="img" with its own text. A drawing
 *  whose single label reads "<camera>. Right: <a> Wrong: <b>" and whose halves are marked (<g class="h-panel right">
 *  from engine/hand.mjs, <g class="zx-half wrong"> from the render scripts) becomes a group labelled by the camera,
 *  holding two images, "Right: <a>" and "Wrong: <b>". Its printed words (Right, Wrong, notes, values) are hidden from
 *  the reader, since the two image labels already say them. Throws if a paired label has no marked halves. */
export function splitHalves(html, where = '') {
  let out = '', i = 0;
  for (;;) {
    const a = html.indexOf('<svg class="hand-svg', i);
    if (a < 0) break;
    let depth = 0, j = a;
    for (const m of html.slice(a).matchAll(/<svg\b|<\/svg>/g)) { depth += m[0] === '</svg>' ? -1 : 1; if (!depth) { j = a + m.index + 6; break; } }
    let svg = html.slice(a, j);
    const open = svg.slice(0, svg.indexOf('>') + 1), lab = open.match(/aria-label="([^"]*)"/)?.[1] ?? '';
    const m = lab.match(/^([\s\S]*?)\s*Right: ([\s\S]*?)\s*Wrong: ([\s\S]*)$/);
    if (m && / role="img"/.test(open)) {
      const halves = svg.match(/<g class="(?:h-panel|zx-half) (?:right|wrong)">/g) ?? [];
      if (halves.length !== 2) throw new Error(`${where}: a right/wrong drawing without two marked halves (${halves.length})`);
      const cam = m[1].replace(/\.$/, '');
      svg = svg.replace(open, open.replace(' role="img"', ' role="group"').replace(/aria-label="[^"]*"/, `aria-label="${cam}"`))
        .replace(/<text /g, '<text aria-hidden="true" ')
        .replace(/<g class="((?:h-panel|zx-half) (right|wrong))">/g, (x, cls, side) => `<g class="${cls}" role="img" aria-label="${side === 'right' ? 'Right: ' + m[2] : 'Wrong: ' + m[3]}">`);
    }
    out += html.slice(i, a) + svg; i = j;
  }
  return out + html.slice(i);
}
/** Tidy one render-script zoom section for the card: its own heading/back row and chip row go (the card draws them
 *  once for every exercise), the long wrist-limit hint goes (one plain line of copy under a hand), every button gets
 *  type="button", and the "This is usually why" link and the page tabs get data hooks for the page script. */
function cleanZoom(html, { api, howto, zoom, pageIdx }) {
  if (api.chipRow) html = html.split(api.chipRow(zoom.key)).join('');
  html = html
    .replace(/<div class="ztop">[\s\S]*?<\/h3><\/div>/, '')
    .replace(/<div class="zoom-top">[\s\S]*?<\/h3><\/div>/, '')
    .replace(/\srole="region" aria-labelledby="zh-[^"]*"/, '');
  const lim = howto.handling?.wrist?.limitText;
  if (lim) html = html.split(`<p class="hint limit">${escR(lim)}</p>`).join('');
  html = html.replace(/<button(?![^>]*\stype=)/g, '<button type="button"');
  if (zoom.feelRow) html = html.replace(/<button type="button" class="(feellink|z-feelrow)"/g, `<button type="button" class="$1" data-feelrow="${esc(zoom.feelRow)}"`);
  // Page buttons: each page carries its own copy of the pager (only the shown page's copy is visible), so they are plain
  // toggle buttons in a group, not an ARIA tablist (a tablist needs one list, roving tabindex and arrow keys).
  html = html.replace(/<div class="pager" role="tablist"/g, '<div class="pager" role="group"')
    .replace(/(<button type="button" class="pager-btn") role="tab" aria-selected=/g, '$1 aria-pressed=');
  if (/role="tab|aria-selected/.test(html)) throw new Error(`${howto.id}/${zoom.key}: tab roles left in a close-up`);
  let k = 0;
  html = html.replace(/<button type="button" class="pager-btn"/g, () => `<button type="button" class="pager-btn" data-page="${k}" id="zb-${zoom.key}-p${pageIdx}-tab${k++}"`);
  html = html.replace(/<button type="button" class="(feellink|z-feelrow)"/g, `<button type="button" id="zb-${zoom.key}-p${pageIdx}-why" class="$1"`);
  html = splitHalves(html, `${howto.id}/${zoom.key}`);
  if (/<button(?![^>]*\sid=)/.test(html)) throw new Error(`${howto.id}/${zoom.key}: a close-up button without an id`);
  if (/ztop|zoom-top|class="chips"|zoom-chips/.test(html)) throw new Error(`${howto.id}/${zoom.key}${pageIdx != null ? ' p' + pageIdx : ''}: chrome not stripped`);
  return html;
}

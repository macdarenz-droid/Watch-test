/** Give every id a fragment defines a per-card prefix, and follow every reference to it (url(#), href, aria-*). */
function prefixIds(html, pre) {
  const ids = new Set([...html.matchAll(/\sid="([^"]+)"/g)].map(m => m[1]));
  const map = id => ids.has(id) ? pre + id : id;
  return html
    .replace(/(\sid=")([^"]+)"/g, (m, a, b) => `${a}${map(b)}"`)
    .replace(/url\((['"]?)#([^)'"]+)\1\)/g, (m, q, b) => `url(${q}#${map(b)}${q})`)
    .replace(/((?:xlink:)?href=")#([^"]+)"/g, (m, a, b) => `${a}#${map(b)}"`)
    .replace(/(aria-(?:labelledby|describedby|controls)=")([^"]+)"/g, (m, a, b) => `${a}${b.split(/\s+/).map(map).join(' ')}"`);
}
const splitTop = s => { const out = []; let d = 0, cur = ''; for (const ch of s) { if (ch === '(') d++; if (ch === ')') d--; if (ch === ',' && !d) { out.push(cur); cur = ''; } else cur += ch; } out.push(cur); return out; };
/** Scope a render script's page CSS to one card's close-ups (page-level rules and @font-face are dropped). */
function scopeCss(css, scope) {
  css = css.replace(/\/\*[\s\S]*?\*\//g, '');
  let out = '', i = 0;
  while (i < css.length) {
    const open = css.indexOf('{', i);
    if (open < 0) break;
    const head = css.slice(i, open).trim();
    let depth = 1, j = open + 1;
    while (depth && j < css.length) { if (css[j] === '{') depth++; else if (css[j] === '}') depth--; j++; }
    const body = css.slice(open + 1, j - 1);
    if (/^@(media|supports)/.test(head)) out += `${head}{${scopeCss(body, scope)}}`;
    else if (/^@keyframes/.test(head)) out += `${head}{${body}}`;
    else if (!head.startsWith('@')) {
      const sels = splitTop(head).map(s => s.trim()).filter(s => s && !/^(html|body|:root)\b/.test(s));
      if (sels.length) out += `${sels.map(s => `${scope} ${s}`).join(',')}{${body.trim()}}\n`;
    }
    i = j;
  }
  return out;
}

/** Load a render script's drawing functions without running its Playwright pass. */
async function loadRenderer(id) {
  const file = join(root, RENDERER[id]), url = pathToFileURL(file).href;
  let src = readFileSync(file, 'utf8');
  const cut = src.indexOf('const { chromium } = createRequire(');
  if (cut < 0) throw new Error(`${id}: render script has no Playwright start to cut at`);
  src = src.slice(0, cut)
    .replace(/import\.meta\.url/g, JSON.stringify(url))
    .replace(/(from\s+|import\s*\(\s*)'(\.{1,2}\/[^']+)'/g, (m, pre, spec) => `${pre}'${new URL(spec, url).href}'`);
  src += `\nexport const __api = { ${API.map(n => `${n}: typeof ${n} === 'undefined' ? undefined : ${n}`).join(', ')} };\n`;
  mkdirSync(genDir, { recursive: true });
  const out = join(genDir, `${id}.mjs`);
  writeFileSync(out, `// GENERATED by artifact/howto-layers.mjs from ${RENDERER[id]} (drawing part only). Do not edit.\n${src}`);
  return (await import(pathToFileURL(out).href)).__api;
}


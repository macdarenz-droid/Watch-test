const PAIN_NAMES = [[/^hand-/, 'wrists and hands'], [/^elbow-/, 'elbows'], [/^knee-/, 'knees'], [/^nape$/, 'back of the neck']];
function feelSection(pre, howto, M) {
  const F = howto.feel, ids = x => x.muscleId;
  const rest = renderFeelMap({ primary: F.primary, secondary: F.secondary, views: ['front', 'back'], id: `${pre}-feel`, shimmer: true });
  const watchIds = new Set(F.watch.map(ids)), priIds = new Set(F.primary.map(ids));
  const marks = [[], []];
  const rows = F.rows.map(r => {
    const watch = (r.at?.muscles ?? []).filter(m => watchIds.has(m) && !priIds.has(m));
    const pain = r.at?.parts ?? [];
    let label = rest.label;
    if (watch.length || pain.length) {
      const m = renderFeelMap({ primary: F.primary, secondary: F.secondary, avoid: watch, pain, views: ['front', 'back'], id: `${pre}-feel-${r.key}`, shimmer: false });
      label = m.label;
      const pn = [...new Set(pain.map(p => PAIN_NAMES.find(([re]) => re.test(p))?.[1] ?? p))];
      if (pn.length) label += ` Marked: ${pn.join(' and ')}.`;
      m.svg.split('</figure>').slice(0, 2).forEach((v, vi) => {
        const w = v.match(/<g class="feel-watch">[\s\S]*?<\/g>/)?.[0] ?? '', p = v.match(/<g class="feel-pain">[\s\S]*?<\/g>/)?.[0] ?? '';
        if (w || p) marks[vi].push(`<g class="feel-mark" data-row="${esc(r.key)}">${w.replace('class="feel-watch"', 'class="feel-quiet"')}${p}${w}</g>`);
      });
    }
    return { r, watch, pain, label };
  });
  let k = 0;
  const mapHtml = rest.html.replace(/<\/svg>/g, s => `${marks[k++]?.join('') ?? ''}${s}`)
    .replace('data-feel-map>', `data-feel-map id="${pre}-feel-map" data-rest-label="${esc(rest.label)}">`);
  const legend = renderFeelLegend({ avoid: true }).replace(/<span>(<svg class="feel-sw sw-watch)/, '<span class="lg-watch" hidden>$1')
    .replace(/<\/div>$/, `<span class="lg-pain" hidden><svg class="feel-sw sw-pain" viewBox="0 0 14 14" aria-hidden="true"><rect x="1.5" y="1.5" width="11" height="11" rx="3"/></svg>Where it may hurt</span></div>`);
  // plan 2.4 / HT9-A3: ONE red-flag node per sheet, in "Risks and when to stop". A row that needs it (architecture 2.7,
  // S6) links to it instead of printing a second copy.
  const RF = { true: 'wrist', shoulder: 'shoulder', knee: 'knee', elbow: 'elbow' };
  const zoomChip = key => howto.zooms.find(z => z.key === key)?.chip;
  const rowsHtml = rows.map(({ r, watch, pain, label }, i) => {
    const flag = r.redFlag ? RF[r.redFlag] : null;
    if (r.redFlag && !flag) throw new Error(`${howto.id}: row ${r.key} red flag ${r.redFlag} missing`);
    return `<li class="fr" data-row="${esc(r.key)}"${i >= FEEL_VISIBLE ? ' data-more hidden' : ''}>`
      + `<button type="button" class="fr-btn" id="${pre}-row-${r.key}" aria-expanded="false" aria-controls="${pre}-row-${r.key}-body" data-label="${esc(label)}"${watch.length ? ' data-watch' : ''}${pain.length ? ' data-pain' : ''}>`
      + `<span>${esc(r.where)}</span>${I.down(18)}</button>`
      + `<div class="fr-body" id="${pre}-row-${r.key}-body" hidden><p><b>Usually means</b>${esc(r.means)}</p><p><b>Fix</b>${esc(r.fix)}</p>`
      + (r.zoom ? `<button type="button" class="fr-show" id="${pre}-row-${r.key}-show" data-zoom="${esc(r.zoom)}">Show me the ${esc(zoomChip(r.zoom).toLowerCase())}${I.arrow(16)}</button>` : '')
      + (flag ? `<button type="button" class="rf-link" id="${pre}-row-${r.key}-flag" data-flag="${flag}" aria-controls="${pre}-redflag-${flag}">${I.alert(16)}When to get it checked</button>` : '')
      + `</div></li>`;
  }).join('');
  const more = F.rows.length - FEEL_VISIBLE;
  const txt = (F.textOnly ?? []).map(m => m.plain).join(' ');
  return `<section class="hw-sec feel" id="${pre}-feel" aria-labelledby="${pre}-feel-h">`
    + `<h4 class="eyebrow" id="${pre}-feel-h" tabindex="-1">Where you should feel it</h4>`
    + `<p class="feel-lead">${esc(F.feelLine)}</p>${mapHtml}${legend}${txt ? `<p class="feel-note">${esc(txt)}</p>` : ''}`
    + `<h5 class="eyebrow fr-head">If you feel it in…</h5><ul class="fr-list">${rowsHtml}</ul>`
    + (more > 0 ? `<button type="button" class="fr-more" id="${pre}-feel-more" aria-expanded="false" data-n="${more}">Show ${more} more</button>` : '')
    + `</section>`;
}


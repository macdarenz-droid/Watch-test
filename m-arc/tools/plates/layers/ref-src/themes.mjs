var THEME_IDS = Object.keys(THEMES);
var DEFAULT_THEME = "silent-black";
function isThemeId(value) {
  return typeof value === "string" && value in THEMES;
}
function themeToCss(theme) {
  const t = theme.tokens;
  const lines = [
    `color-scheme:${t.colorScheme}`,
    `--bg:${t.bg}`,
    `--surface-1:${t.surface1}`,
    `--surface-2:${t.surface2}`,
    `--surface-3:${t.surface3}`,
    `--border-subtle:${t.borderSubtle}`,
    `--border:${t.border}`,
    `--border-strong:${t.borderStrong}`,
    `--text:${t.text}`,
    `--text-2:${t.text2}`,
    `--text-3:${t.text3}`,
    `--accent:${t.accent}`,
    `--accent-soft:${t.accentSoft}`,
    `--on-accent:${t.onAccent}`,
    `--positive:${t.positive}`,
    `--warning:${t.warning}`,
    `--negative:${t.negative}`,
    `--info:${t.info}`,
    `--shadow:${t.shadow}`,
    `--map-body:${t.mapBody}`,
    `--map-line:${t.mapLine}`,
    `--radius-sm:${theme.radius.sm}`,
    `--radius-md:${theme.radius.md}`,
    `--radius-lg:${theme.radius.lg}`,
    `--radius-xl:${theme.radius.xl}`,
    `--font:${theme.font}`,
    // I14: restates styles.css's 75/25 --accent-text default, or overrides it for a theme whose
    // probed worst case measures under 4.5:1 there. This rule's `[data-theme]` attribute selector
    // matches :root's specificity, but the theme <style> tag (theme/engine.ts) is inserted after
    // styles.css, so it wins the tie either way.
    `--accent-text:color-mix(in srgb, var(--accent) ${t.accentTextPct}%, var(--text))`,
    // FG-1: form-guide figure tokens.
    `--mistake:${t.mistake}`,
    `--target:${t.target}`,
    `--help:${t.help}`,
    `--quiet:${t.quiet}`,
    `--pants:${t.pants}`,
    `--pants-hi:${t.pantsHi}`,
    `--pants-sh:${t.pantsSh}`,
    `--ink:${t.ink}`,
    `--iron:${t.iron}`,
    `--iron-hi:${t.ironHi}`,
    `--iron-sh:${t.ironSh}`,
    `--eye:${t.eye}`,
    `--floor:${t.floor}`,
    `--guide:${t.guide}`
  ];
  return `[data-theme="${theme.id}"]{${lines.join(";")}}`;
}
function allThemesCss() {
  return THEME_IDS.map((id) => themeToCss(THEMES[id])).join("\n");
}
export {
  DEFAULT_THEME,
  THEMES,
  THEME_IDS,
  allThemesCss,
  isThemeId,
  themeToCss
};

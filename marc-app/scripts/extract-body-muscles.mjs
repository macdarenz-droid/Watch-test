// Generate src/svg/bodyMuscles.ts from the body-muscles package (Apache 2.0).
// Run: node scripts/extract-body-muscles.mjs
import { writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const { FRONT_MUSCLES, BACK_MUSCLES } = require('body-muscles');

/** Library part id prefix → M/ARC muscle key. Unlisted parts are plain body. */
const MAP = [
  ['chest-upper', 'upper_chest'], ['chest-lower', 'chest'],
  ['shoulder-front', 'front_delts'], ['shoulder-side', 'side_delts'], ['deltoid-rear', 'rear_delts'],
  ['biceps', 'biceps'], ['triceps', 'triceps'], ['forearm', 'forearms'],
  ['abs-', 'abs'], ['obliques', 'obliques'], ['serratus', 'core'], ['hip-flexor', 'hip_flexors'],
  ['quads', 'quads'], ['adductors', 'adductors'], ['hamstrings', 'hamstrings'], ['calves', 'calves'],
  ['gluteus-maximus', 'glutes'], ['gluteus-medius', 'abductors'],
  ['traps-upper', 'upper_traps'], ['traps-mid', 'mid_back'], ['traps-lower', 'mid_back'], ['lats', 'lats'],
  ['lower-back', 'lower_back'],
];
const muscleFor = id => MAP.find(([p]) => id.startsWith(p))?.[1] ?? null;
const conv = list => list.map(m => ({ id: m.id, muscle: muscleFor(m.id), d: m.path.replace(/\s+/g, ' ').trim() }));
const front = conv(FRONT_MUSCLES), back = conv(BACK_MUSCLES);
const out = `/**
 * Body parts for the muscle map, generated by scripts/extract-body-muscles.mjs
 * from the body-muscles package (Ivan Vulović, Apache License 2.0, see
 * THIRD_PARTY_NOTICES.md). Do not edit by hand.
 */
import type { MuscleId } from '@/data/muscles';

export interface BodyPart { id: string; muscle: MuscleId | null; d: string }
export const FRONT_VIEWBOX = '0 0 35 93';
export const BACK_VIEWBOX = '37 0 35 93';
export const FRONT_PARTS: BodyPart[] = ${JSON.stringify(front)};
export const BACK_PARTS: BodyPart[] = ${JSON.stringify(back)};
`;
writeFileSync('src/svg/bodyMuscles.ts', out);
const mapped = [...front, ...back].filter(p => p.muscle).length;
console.log(`front ${front.length}, back ${back.length}, mapped ${mapped}`);
console.log('unmapped:', [...front, ...back].filter(p => !p.muscle).map(p => p.id).join(', '));
